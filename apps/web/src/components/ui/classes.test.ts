import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { compile } from 'tailwindcss';
import { describe, expect, it } from 'vitest';
import { NO_DATA, stateStyle } from '../../domain/states.ts';
import { TONE_CLASS, badgeShape } from './badge.tsx';
import { PRIORITY_COLORS } from '../priority-badge.tsx';
import { buttonClass } from './button.tsx';
import { CALLOUT_LOOK } from './callout.tsx';
import { CARD_TONE_BAR } from './card.tsx';
import { STAT_VALUE_TONE } from './stat.tsx';

/**
 * UX-1c (#315): every class the primitives build their look from is one Tailwind generates from
 * the tokens of `index.css`: a misspelt token (`bg-alarm-sofft`) or a palette class would render
 * nothing, and no unit test of the DOM would notice.
 */
const CSS_PATH = join(import.meta.dirname, '..', '..', 'index.css');
const css = readFileSync(CSS_PATH, 'utf8');

const STATES = [
  'Running',
  'Idle',
  'Setup',
  'PlannedStop',
  'Maintenance',
  'Off',
  'Starved',
  'Blocked',
  'Stopped',
  'Down',
];

function candidates(): string[] {
  const strings = [
    ...(['primary', 'secondary', 'ghost', 'danger', 'dangerSolid'] as const).flatMap((variant) =>
      (['sm', 'md', 'lg', 'touch'] as const).flatMap((size) => [
        buttonClass({ variant, size, fullWidth: true }),
        buttonClass({ variant, size, iconOnly: true }),
      ]),
    ),
    ...(['sm', 'md', 'lg'] as const).map((size) => badgeShape(size)),
    ...Object.values(TONE_CLASS).flatMap((variants) => Object.values(variants)),
    ...STATES.map((state) => stateStyle(state).className),
    stateStyle('Warp').className,
    NO_DATA.className,
    ...Object.values(PRIORITY_COLORS),
    ...Object.values(CARD_TONE_BAR),
    ...Object.values(STAT_VALUE_TONE),
    ...Object.values(CALLOUT_LOOK),
  ];
  return [...new Set(strings.flatMap((s) => s.split(/\s+/)).filter(Boolean))];
}

describe('the primitives’ classes', async () => {
  const require = createRequire(join(import.meta.dirname, 'classes.test.ts'));
  const tailwindDir = dirname(require.resolve('tailwindcss/package.json'));
  const compiler = await compile(css, {
    base: dirname(CSS_PATH),
    loadStylesheet: (id: string) => {
      const path = id === 'tailwindcss' ? join(tailwindDir, 'index.css') : id;
      return Promise.resolve({ path, base: dirname(path), content: readFileSync(path, 'utf8') });
    },
  });
  it('are all generated by Tailwind from the tokens', () => {
    // The compiler's output grows with every class it generates (it keeps the earlier ones).
    const missing = candidates().filter((candidate) => {
      const before = compiler.build([]);
      return compiler.build([candidate]) === before;
    });
    expect(missing).toEqual([]);
  });

  it('name no raw palette colour', () => {
    const palette =
      /(?:^|:)(?:bg|text|border|border-l)-(?:(?:slate|gray|zinc|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d+|white|black)$/;
    expect(candidates().filter((c) => palette.test(c))).toEqual([]);
  });

  it('colour every machine state from its own state tokens', () => {
    for (const state of STATES) {
      const key = state === 'PlannedStop' ? 'planned-stop' : state.toLowerCase();
      expect(stateStyle(state).className.split(' '), state).toEqual(
        expect.arrayContaining([
          `bg-state-${key}-fill`,
          `text-state-${key}-ink`,
          `border-state-${key}-border`,
        ]),
      );
    }
  });
});
